#!/usr/bin/env python3
"""Export GAME symbols for the segment E assemble (src/sege.asm -> gamee.prg).

Segment E is assembled on its own, after GAME, like the QSAVE overlay. It
sources mem.asm / zp.asm itself; everything else it names (routines, BSS that
lives in game modules, per-module equates) comes from game.lbl. Every GAME
label is exported except the ones the E source tree defines itself.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from mkreloc import parse_labels

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
SEGE = SRC / "sege.asm"
OUT = SRC / "esyms.asm"

LABEL_LINE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\b")
SOURCE_LINE = re.compile(r'!source\s+"([^"]+)"')
SKIP_PREFIX = ("smc_", "mod_", "seg_")


def e_sources(root: Path = SEGE) -> list[Path]:
    """sege.asm and everything it sources, without the generated esyms.asm."""
    seen: list[Path] = []

    def walk(path: Path) -> None:
        path = path.resolve()
        if path in seen or path == OUT.resolve() or not path.is_file():
            return
        seen.append(path)
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            m = SOURCE_LINE.search(line)
            if m and not line.lstrip().startswith(";"):
                walk(path.parent / m.group(1))

    walk(root)
    return seen


def e_defined() -> set[str]:
    names: set[str] = set()
    for path in e_sources():
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if not line or line[0].isspace():
                continue
            m = LABEL_LINE.match(line)
            if m:
                names.add(m.group(1))
    return names


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate segment E GAME symbols")
    ap.add_argument("--labels", default="game.lbl")
    args = ap.parse_args()
    path = Path(args.labels)
    if not path.is_file():
        path = ROOT / path
    labels = parse_labels(path)
    own = e_defined()
    rows = sorted(
        (name, addr)
        for name, addr in labels.items()
        if name not in own and not name.startswith(SKIP_PREFIX)
    )
    lines = ["; Generated by tools/genesyms.py — GAME symbols for segment E. Do not edit."]
    # No leading zeros: ACME reads "$0004" as a forced 16-bit value and then
    # rejects it as an immediate operand.
    lines.extend(f"{name}\t= ${addr:x}" for name, addr in rows)
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(rows)} symbols)")


if __name__ == "__main__":
    main()
