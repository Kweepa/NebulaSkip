#!/usr/bin/env python3
"""Pack editor/font.json into a 2K C64 charset (ASCII-indexed 8×8 UDGs)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "editor" / "font.json"
DATA = ROOT / "src" / "uifont_data.asm"
OUT = ROOT / "src" / "uifont.asm"

COUNT = 96
CELL = 8
# Glyph i is ASCII 32 + i. Each row is a hex byte, MSB = leftmost pixel.
ASCII_BASE = 32


def bchunk(data: list[int], w: int = 16) -> str:
    lines = []
    for i in range(0, len(data), w):
        chunk = data[i : i + w]
        lines.append("\t!byte " + ",".join(f"${b:02x}" for b in chunk))
    return "\n".join(lines) + "\n"


def load_glyphs() -> dict[int, list[int]]:
    data = json.loads(FONT.read_text(encoding="utf-8"))
    out: dict[int, list[int]] = {}
    for pos, g in enumerate(data["glyphs"]):
        code = int(g.get("code", ASCII_BASE + pos))
        if not ASCII_BASE <= code < ASCII_BASE + COUNT:
            raise SystemExit(f"{FONT}: glyph code {code} outside {ASCII_BASE}..{ASCII_BASE + COUNT - 1}")
        rows = [int(r, 16) if isinstance(r, str) else int(r) for r in g["rows"]]
        if len(rows) != CELL or any(not 0 <= r <= 255 for r in rows):
            raise SystemExit(f"{FONT}: glyph {code} needs {CELL} row bytes")
        out[code] = rows
    return out


def main() -> None:
    glyphs = load_glyphs()

    charset = [0] * 2048
    for code, rows in glyphs.items():
        off = code * CELL
        charset[off : off + CELL] = rows

    DATA.write_text(
        "; Auto-generated by tools/genuifont.py — do not edit\n"
        f"; {FONT.name}: {COUNT} glyphs of {CELL}x{CELL}, placed at ASCII {ASCII_BASE}..\n"
        "uifont_udgs\n"
        + bchunk(charset),
        encoding="utf-8",
    )
    print(f"Wrote {DATA} ({len(charset)} bytes)")

    OUT.write_text(
        "!cpu 6502\n"
        '!to "fnt.prg", cbm\n'
        "; Auto-generated by tools/genuifont.py — do not edit\n"
        "*= $F800\n"
        '!source "uifont_data.asm"\n',
        encoding="utf-8",
    )
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
