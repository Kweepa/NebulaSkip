"""Emit unrolled mode-E line bodies into src/_a8line_bodies.asm."""
from pathlib import Path

# Mode E: four colour clocks per byte, linear 32-byte rows. No charset, no y=64.
A8_MASKS = [0xC0, 0x30, 0x0C, 0x03]
A8_OUT = Path(__file__).resolve().parents[1] / "src" / "_a8line_bodies.asm"


def y_step(down: bool) -> str:
    """One row in Y (row offset inside the page, a multiple of 32). C is not touched.

    Down: the low five bits of Y are clear, so ora #$1f / iny is +32 and Z flags
    the wrap into the next page. Up: borrow the page first, then dey / and #$e0.
    Every caller needs C=1 afterwards (the error update's adc always wraps: the
    true sum e-d1+d2 >= 0 with d2 >= d1), and nothing here changes it.
    """
    if down:
        return "\ttya\n\tora #$1f\n\ttay\n\tiny\n\tbne +\n\tinc colptr+1\n+\n"
    return "\ttya\n\tbne +\n\tdec colptr+1\n+\n\tdey\n\ttya\n\tand #$e0\n\ttay\n"


def shallow(prefix: str, down: bool) -> str:
    parts: list[str] = []
    for i, mask in enumerate(A8_MASKS):
        n = f"{prefix}{i}"
        nxt = f"{prefix}{(i + 1) & 3}"
        step = y_step(down)
        if i < 3:
            tail = f"""	sta err_l
{step}	jmp {nxt}
{n}sk
	sta err_l
"""
        else:
            tail = f"""	sta err_l
{step}	jmp {n}x
{n}sk
	sta err_l
{n}x
	inc colptr
	jmp {prefix}0
"""
        parts.append(
            f"""{n}
	lda (colptr),y
	ora #${mask:02x}
	sta (colptr),y
	dex
	bne {n}c
	rts
{n}c
	lda err_l
	sbc dy
	bcs {n}sk
	adc dx
{tail}"""
        )
    return "".join(parts)


def steep(prefix: str, down: bool) -> str:
    parts: list[str] = []
    for i, mask in enumerate(A8_MASKS):
        n = f"{prefix}{i}"
        step = y_step(down)
        parts.append(f"{n}s\n\tsta err_l\n")
        parts.append(
            f"""{n}
	lda (colptr),y
	ora #${mask:02x}
	sta (colptr),y
	dex
	bne {n}c
	rts
{n}c
{step}	lda err_l
	sbc dx
	bcs {n}s
	adc dy
"""
        )
        if i == 3:
            parts.append(f"\tsta err_l\n\tinc colptr\n\tjmp {prefix}0\n")
    return "".join(parts)


def a8_table(name: str, prefix: str) -> str:
    lo = ",".join(f"<{prefix}{i}" for i in range(4))
    hi = ",".join(f">{prefix}{i}" for i in range(4))
    return f"{name}_l\t!byte {lo}\n{name}_h\t!byte {hi}\n"


def emit_a8() -> None:
    parts = [
        "; Auto-generated by tools/genlinebodies.py — mode-E line bodies\n",
        "; Four masks, chained C (set on entry, kept by every step), countdown in X.\n",
        "; colptr = page + column byte (4..27). Y = row offset in the page, (y & 7) << 5.\n",
        "; A row is 32 on Y and the page byte follows a wrap. Four pixels then inc colptr.\n",
        "; Each body starts lda (colptr),y / ora #mask: rocket.asm patches the ora opcode.\n",
        "; ---- X major +Y ----\n",
        a8_table("esdn", "esd"),
        shallow("esd", True),
        "; ---- X major -Y ----\n",
        a8_table("esup", "esu"),
        shallow("esu", False),
        "; ---- Y major +Y ----\n",
        a8_table("etdn", "etd"),
        steep("etd", True),
        "; ---- Y major -Y ----\n",
        a8_table("etup", "etu"),
        steep("etu", False),
    ]
    A8_OUT.write_text("".join(parts), encoding="utf-8")
    print(f"Wrote {A8_OUT}")


def main() -> None:
    emit_a8()


if __name__ == "__main__":
    main()
