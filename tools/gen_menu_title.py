#!/usr/bin/env python3
"""Pack ui/NEBULASKIPlogo.png as the menu logo.

The PNG is 320x32 with 2px-wide pixels (160x32 mode E). It has three colours:
black, orange (the lettering and the underline) and purple (the outline).
The logo is centred vertically in the 7 mode-E rows (56 lines) so the control
page layout under it is unchanged. Each scanline gets its own GTIA palette,
which is how the orange fades from yellow at the top to red at the bottom.
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PNG = ROOT / "ui" / "NEBULASKIPlogo.png"
OUT = ROOT / "src" / "menu_title.asm"
PREVIEW = ROOT / "ui" / "nebulalogo_preview.png"

ROWS = 7
OUT_H = ROWS * 8
COLS = 40
LEFT = (40 - COLS) // 2
PIX = COLS * 4

SRC_W, SRC_H = 320, 32
PAD_TOP = (OUT_H - SRC_H) // 2

ORANGE_SRC = (255, 164, 28)
PURPLE_SRC = (112, 109, 235)

# NTSC GTIA bytes (runtime runs these through a8_to_pal), top to bottom of the
# logo: yellow, gold, orange, red-orange, red.
GRADIENT = (0x1E, 0x2C, 0x2A, 0x3A, 0x36)
PURPLE = 0x96

# RGB approximations for the preview PNG only.
PREVIEW_RGB = {
	0x1E: (0xFC, 0xE8, 0x40),
	0x2C: (0xE8, 0xA0, 0x20),
	0x2A: (0xD8, 0x80, 0x20),
	0x3A: (0xD0, 0x58, 0x30),
	0x36: (0xB8, 0x30, 0x30),
	PURPLE: (0x58, 0x60, 0xD8),
	0x00: (0, 0, 0),
}


def orange_for(sy: int) -> int:
	return GRADIENT[min(len(GRADIENT) - 1, sy * len(GRADIENT) // SRC_H)]


def fmt(data: list[int], per: int = 16) -> list[str]:
	lines = []
	for i in range(0, len(data), per):
		chunk = data[i : i + per]
		lines.append("\t!byte " + ",".join(f"${b:02x}" for b in chunk))
	return lines


def main() -> None:
	im = Image.open(PNG).convert("RGB")
	if im.size != (SRC_W, SRC_H):
		raise SystemExit(f"{PNG.name}: expected {SRC_W}x{SRC_H}, got {im.size}")
	px = im.load()

	# Per output scanline: PIX slot indices (0 black, 1 orange, 2 purple) and
	# the 4-colour palette [bk, pf0, pf1, pf2].
	lines_slot: list[list[int]] = []
	palettes: list[list[int]] = []
	for oy in range(OUT_H):
		sy = oy - PAD_TOP
		if not 0 <= sy < SRC_H:
			lines_slot.append([0] * PIX)
			palettes.append([0x00, 0x00, 0x00, 0x00])
			continue
		row = []
		for x in range(PIX):
			if px[x * 2, sy] != px[x * 2 + 1, sy]:
				raise SystemExit(f"{PNG.name}: row {sy} col {x * 2} is not a 2px pair")
			c = px[x * 2, sy]
			if c == (0, 0, 0):
				row.append(0)
			elif c == ORANGE_SRC:
				row.append(1)
			elif c == PURPLE_SRC:
				row.append(2)
			else:
				raise SystemExit(f"{PNG.name}: unexpected colour {c} at ({x * 2},{sy})")
		lines_slot.append(row)
		o = orange_for(sy)
		palettes.append([0x00, o, PURPLE, o])

	cells: list[int] = []
	for cy in range(ROWS):
		for cx in range(COLS):
			for s in range(8):
				oy = cy * 8 + s
				byte = 0
				for p in range(4):
					byte |= lines_slot[oy][cx * 4 + p] << (6 - 2 * p)
				cells.append(byte)

	bk = [p[0] for p in palettes]
	pf0 = [p[1] for p in palettes]
	pf1 = [p[2] for p in palettes]
	pf2 = [p[3] for p in palettes]

	out = [
		f"; Auto-generated by tools/gen_menu_title.py from {PNG.name}",
		f"; {PIX}x{OUT_H} mode-E logo. title_src_* is one GTIA byte per scanline (NTSC).",
		"TITLE_SPR_COUNT\t= 0",
		f"MENU_TITLE_LEFT\t= {LEFT}",
		f"MENU_TITLE_COLS\t= {COLS}",
		f"MENU_TITLE_ROWS\t= {ROWS}",
		"MENU_TITLE_PAD_Y\t= 0",
		"",
		"title_spr_xmsb\t!byte $00",
		"title_spr_x\t!byte $00",
		"",
		"title_src_pf0",
	]
	out.extend(fmt(pf0))
	out.append("title_src_pf1")
	out.extend(fmt(pf1))
	out.append("title_src_pf2")
	out.extend(fmt(pf2))
	out.append("title_src_bk")
	out.extend(fmt(bk))
	out.append("")
	out.append("menu_title_data")
	out.extend(fmt(cells))
	out.append("")
	out.append("menu_title_spr")
	out.append("")
	OUT.write_text("\n".join(out) + "\n", encoding="utf-8")

	prev = Image.new("RGB", (160, OUT_H), (0, 0, 0))
	pp = prev.load()
	for oy in range(OUT_H):
		pal = palettes[oy]
		for x in range(PIX):
			pp[LEFT * 4 + x, oy] = PREVIEW_RGB[pal[lines_slot[oy][x]]]
	big = prev.resize((160 * 3, OUT_H * 3), Image.Resampling.NEAREST)
	big.save(PREVIEW)
	print(f"wrote {OUT.relative_to(ROOT)} rows={ROWS} + {PREVIEW.relative_to(ROOT)}")


if __name__ == "__main__":
	main()
