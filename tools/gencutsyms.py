#!/usr/bin/env python3
"""Export the GAME entry points the cutscene overlay (src/a8cutscene.asm) calls."""

from __future__ import annotations

import argparse
from pathlib import Path

from mkreloc import parse_labels

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "cutsyms.asm"

REQUIRED = [
    "draw_world_prep",
    "wait_draw_free",
    "clear_draw",
    "draw_world",
    "update_frustum",
    "mesh_ne",
    "plot_pixel",
    "apply_show",
    "calc_frame_dt",
    "hud_print",
    "set_draw_ptrs",
    "apply_room_palette",
    "cut_draw_item",
    "vbi_count_l",
    "vbi_count_h",
    "vbi_last_l",
    "vbi_last_h",
    "ITEM_BIAS",
    "amb_on",
]


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate cutscene overlay GAME symbols")
    ap.add_argument("--labels", default="game.lbl")
    args = ap.parse_args()
    path = Path(args.labels)
    if not path.is_file():
        path = ROOT / path
    labels = parse_labels(path)
    missing = [name for name in REQUIRED if name not in labels]
    if missing:
        raise SystemExit(f"{path}: missing cutscene symbols: {', '.join(missing)}")
    lines = ["; Generated by tools/gencutsyms.py - GAME entries for the cutscene overlay"]
    # Unpadded hex: ACME treats $0001 as a forced 16-bit value (immediate operands would fail).
    lines.extend(f"{name}\t= ${labels[name]:x}" for name in REQUIRED)
    lines.append("")
    text = "\n".join(lines)
    if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:  # keep the mtime when unchanged
        OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(REQUIRED)} symbols)")


if __name__ == "__main__":
    main()
