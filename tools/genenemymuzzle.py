#!/usr/bin/env python3
"""Pack editor/sprites.json enemy_muzzle_0..2 → src/enemy_muzzle.asm.

One phase-0 rect per LOD. X is the smallest multiple of 8 hires that
covers the ink; Y is the ink span. Header x/y are the crop inside the
24×21 whose top-left is the tip minus EMUZ_OX/EMUZ_OY.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from sprmask import bchunk  # noqa: E402
from spritejson import load_sprites, pack  # noqa: E402

OUT = ROOT / "src" / "enemy_muzzle.asm"
N = 3


def main() -> None:
    parts = [
        "; Auto-generated by tools/genenemymuzzle.py — do not edit\n",
        "; One rect: x_byte, y, width, height, then width*height row-major bytes.\n",
        "; x_byte/y crop the 24×21 whose origin is tip−EMUZ_OX/EMUZ_OY.\n",
        "; Ink %11, clear %00. Distance LOD 0 = near … 2 = far.\n",
        "; Source: editor/sprites.json (enemy_muzzle_0..2)\n",
    ]
    sprites = load_sprites()
    sizes = []
    for i in range(N):
        packed = pack(sprites, f"enemy_muzzle_{i}")
        sizes.append(len(packed))
        parts.append(f"spr_emuz_{i}\n")
        parts.append(bchunk(packed))
        parts.append("\n")
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} mode-E {sizes}")


if __name__ == "__main__":
    main()
