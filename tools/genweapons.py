#!/usr/bin/env python3
"""Pack the pistol, its muzzle flash and the crosshair → src/weapon_spr.asm.

X is clipped to a multiple of 8 hires (phase 0). Two hires bits are one
colour-clock pixel, stored row-major. The body is inverted (ink %00, clear
%11) and ANDed on, so the gun is black. The flash is ink %11 / clear %00.

    python tools/genweapons.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from sprmask import (  # noqa: E402
    H,
    W,
    bchunk,
    load_png_1bit,
    pack_clipped,
)

PNG_DIR = ROOT / "assets" / "weapons"
OUT = ROOT / "src" / "weapon_spr.asm"

# label, png, viewport-relative hires x (VIC x − 88), dy added to weapon y.
FLASHES = [
    ("spr_muzzle_b", "muzzle_flash.png", 172 - 88, -20),
]

# pistol_lines.png is 2×1 pixels. Even origin, so each pair lands on one
# mode-E pixel. Columns 12–13 sit on the muzzle stem (clock 47).
XHAIR_CX = 96				# viewport centre, hires x / row
XHAIR_CY = 64
PISTOL_OX = 10


def line_canvas(name: str, ox: int, width: int, height: int | None = None) -> list[list[int]]:
    """Line-art PNG copied at ox. Even origin pairs the 2×1 pixels.

    height set: the PNG must be exactly that tall. Otherwise any h≤H is accepted.
    """
    path = PNG_DIR / name
    if not path.is_file():
        raise SystemExit(f"missing {path}")
    from PIL import Image

    im = Image.open(path).convert("RGB")
    iw, ih = im.size
    bad_h = ih != height if height is not None else ih > H
    if iw != width or bad_h or ox + iw > W:
        want_h = str(height) if height is not None else f"h≤{H}"
        raise SystemExit(
            f"{path.name}: expected {width}×{want_h} at x={ox}, got {iw}×{ih}"
        )
    pix = [[0] * W for _ in range(H)]
    src = im.load()
    for y in range(ih):
        for x in range(iw):
            r, g, b = src[x, y][:3]
            if r > 16 or g > 16 or b > 16:
                pix[y][ox + x] = 1
    print(f"  occupancy {path.stem}: {path.name} at x={ox}")
    return pix


def crosshair_rect() -> list[int]:
    """ui/crosshair.png, black pixels = ink, centred on the 192x128 viewport.

    8 hires wide, so the centre (96) falls mid-byte: origin 92 gives a
    2-byte rect at column 11 with the glyph shifted four hires inside it.
    """
    path = ROOT / "ui" / "crosshair.png"
    if not path.is_file():
        raise SystemExit(f"missing {path}")
    from PIL import Image

    im = Image.open(path).convert("RGB")
    iw, ih = im.size
    pix = [[0] * iw for _ in range(ih)]
    src = im.load()
    for y in range(ih):
        for x in range(iw):
            r, g, b = src[x, y][:3]
            if r <= 16 and g <= 16 and b <= 16:
                pix[y][x] = 1
    print(f"  occupancy crosshair: {path.name} {iw}×{ih}")
    return pack_clipped(
        pix,
        black=True,
        x_origin=XHAIR_CX - iw // 2,
        y_origin=XHAIR_CY - ih // 2,
        name="crosshair",
    )


def flash_pix(png_name: str) -> list[list[int]]:
    path = PNG_DIR / png_name
    if not path.is_file():
        raise SystemExit(f"missing {path}")
    return load_png_1bit(path, 24, 21)


def emit_bytes(label: str, data: list[int]) -> list[str]:
    return [label, bchunk(data).rstrip(), ""]


def rect_note(data: list[int]) -> str:
    xb, yb, bw, bh = data[:4]
    if yb >= 128:
        yb -= 256
    return f"{bw * 8}x{bh} @ {xb * 8},{yb} ({len(data)}B)"


def main() -> None:
    pist_pix = line_canvas("pistol_lines.png", PISTOL_OX, 24)
    pist_b = pack_clipped(pist_pix, black=True, name="pist")
    flashes = [
        (label, pack_clipped(flash_pix(png), x_origin=ox, y_origin=dy, name=label))
        for label, png, ox, dy in FLASHES
    ]

    parts = [
        "; Generated by tools/genweapons.py from assets/weapons — do not edit",
        "; One rect: x_byte, y, width, height, then width*height row-major bytes.",
        "; X is a multiple of 8 hires (phase 0). The body is inverted (ink %00, clear %11).",
        "; The flash is ink %11 / clear %00. Phase 1 ORs line colour; phase 2 writes %10.",
        "",
    ]
    parts += emit_bytes("spr_pist_b", pist_b)
    for label, data in flashes:
        parts += emit_bytes(label, data)
    xhair_b = crosshair_rect()
    parts += emit_bytes("spr_xhair_b", xhair_b)

    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    print(f"  pist {rect_note(pist_b)}")
    for label, data in flashes:
        print(f"  {label}: {rect_note(data)}")
    print(f"  xhair {rect_note(xhair_b)}")


if __name__ == "__main__":
    main()
