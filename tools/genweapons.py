#!/usr/bin/env python3
"""Pack the pistol, its muzzle flash, the jump cursor and the scan rig → src/weapon_spr.asm.

Art comes from editor/sprites.json (the editor's Sprites tab); placement of each
sprite's canvas is in tools/spritejson.py. X is clipped to a multiple of 8 hires
(phase 0). Two hires bits are one colour-clock pixel, stored row-major. The body
is inverted (ink %00, clear %11) and ANDed on, so the gun is black. The flash is
ink %11 / clear %00. The scan rig shares the pistol canvas and is stamped in its place in
scan mode; a blank rig is a height-0 rect.

    python tools/genweapons.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from sprmask import bchunk  # noqa: E402
from spritejson import load_sprites, pack  # noqa: E402

OUT = ROOT / "src" / "weapon_spr.asm"

# asm label, sprite id
FLASHES = [
    ("spr_muzzle_b", "muzzle_flash"),
]


def emit_bytes(label: str, data: list[int]) -> list[str]:
    return [label, bchunk(data).rstrip(), ""]


def rect_note(data: list[int]) -> str:
    xb, yb, bw, bh = data[:4]
    if yb >= 128:
        yb -= 256
    return f"{bw * 8}x{bh} @ {xb * 8},{yb} ({len(data)}B)"


def main() -> None:
    sprites = load_sprites()
    pist_b = pack(sprites, "pistol")
    flashes = [(label, pack(sprites, sid)) for label, sid in FLASHES]
    xhair_b = pack(sprites, "jump_cursor")
    scan_b = pack(sprites, "scan_rig", required=False)

    parts = [
        "; Generated by tools/genweapons.py from editor/sprites.json — do not edit",
        "; One rect: x_byte, y, width, height, then width*height row-major bytes.",
        "; X is a multiple of 8 hires (phase 0). The body is inverted (ink %00, clear %11).",
        "; The flash is ink %11 / clear %00. Phase 1 ORs line colour; phase 2 writes %10.",
        "",
    ]
    parts += emit_bytes("spr_pist_b", pist_b)
    for label, data in flashes:
        parts += emit_bytes(label, data)
    parts += emit_bytes("spr_xhair_b", xhair_b)
    # Blank rig: height 0 rect, which stamp_scanrig skips.
    parts += emit_bytes("spr_scanrig_b", scan_b or [0, 0, 1, 0])

    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    print(f"  pist {rect_note(pist_b)}")
    for label, data in flashes:
        print(f"  {label}: {rect_note(data)}")
    print(f"  xhair {rect_note(xhair_b)}")
    print(f"  scanrig {rect_note(scan_b) if scan_b else 'blank (height-0 rect)'}")


if __name__ == "__main__":
    main()
